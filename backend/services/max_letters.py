"""Тексты писем бота. Имя подставляется из анкеты, не одно на всех."""

from __future__ import annotations

from backend.services.max_funnel import is_just_plot, is_skip

_GENITIVE = {
    "маме": "мамы",
    "папе": "папы",
    "жене": "жены",
    "мужу": "мужа",
    "парню": "парня",
    "девушке": "девушки",
    "дружбану": "дружбана",
    "подружке": "подружки",
    "родственнику": "родственника",
    "ребёнку": "ребёнка",
    "половинке": "половинки",
}


def _role(contact: dict) -> str:
    if (contact.get("segment") or "") == "business":
        return "business"
    whom = (contact.get("brief_whom") or "").strip()
    if is_just_plot(whom, contact.get("segment") or "") or not whom:
        return "plain"
    return "gift"


def _whom(contact: dict) -> str:
    if _role(contact) != "gift":
        return ""
    return (contact.get("brief_whom") or "").strip()


def _for(whom: str) -> str:
    gen = _GENITIVE.get(whom)
    if gen:
        return f"для {gen}"
    return whom


def _detail(contact: dict) -> str:
    raw = " ".join((contact.get("brief_detail") or "").split())
    if not raw or is_skip(raw):
        return ""
    if len(raw) > 80:
        raw = raw[:79].rstrip() + "…"
    return raw


def studio_letter(contact: dict, step: int) -> str:
    """Письмо тому, кто песню ещё не запустил. step 0..4."""
    role = _role(contact)
    whom = _whom(contact)
    detail = _detail(contact)
    n = step if step < 4 else 4
    if role == "business":
        return _business_studio(n, detail)
    if n == 0:
        if whom:
            return (
                f"Черновик {whom} уже есть. Нажми — через пару минут "
                "можно услышать, как это звучит."
            )
        return (
            "Черновик уже есть. Нажми — через пару минут "
            "можно услышать, как это звучит."
        )
    if n == 1:
        if detail and whom:
            return (
                f"{detail}. Из этого уже получается строчка {whom}. "
                "Можно поправить — или сразу услышать, как она поётся."
            )
        if detail:
            return (
                f"{detail}. Из этого уже получается строчка. "
                "Можно поправить — или сразу услышать, как она поётся."
            )
        if whom:
            return (
                f"Песня {whom} пока без голоса. "
                "Пара минут — и можно услышать первый вариант."
            )
        return "Черновик пока без голоса. Пара минут — и можно услышать первый вариант."
    if n == 2:
        if whom:
            return (
                f"Будет два варианта {_for(whom)}. Обычно один теплее, другой смелее. "
                "Можно услышать оба."
            )
        return (
            "Будет два варианта. Обычно один теплее, другой смелее. "
            "Можно услышать оба."
        )
    if n == 3:
        if whom:
            return (
                f"Представь, как {whom} это включается на кухне. "
                "Пара минут — и можно услышать песню до того, как дарить."
            )
        return "Пара минут — и можно услышать, как черновик звучит. Он всё ещё в студии."
    if whom:
        return f"Вечер как раз для этого. Песня {whom} может зазвучать уже сегодня."
    return "Вечер как раз для этого. Песня может зазвучать уже сегодня."


def _business_studio(step: int, detail: str) -> str:
    if step == 0:
        return (
            "Черновик ролика уже в студии. "
            "Пара минут — и можно услышать, как он звучит."
        )
    if step == 1:
        if detail:
            return (
                f"{detail}. Из этого уже получается строчка. "
                "Можно поправить — или сразу услышать, как она поётся."
            )
        return "Ролик пока без звука. Пара минут — и можно услышать, как он звучит."
    if step == 2:
        return (
            "Будет два варианта ролика. Обычно один теплее, другой смелее. "
            "Можно услышать оба."
        )
    if step == 3:
        return (
            "Пара минут — и можно услышать, как ролик садится на видео. "
            "Черновик всё ещё в студии."
        )
    return "Вечер как раз, чтобы услышать ролик. Черновик уже в студии."


def ready_letter(contact: dict) -> str:
    role = _role(contact)
    whom = _whom(contact)
    if role == "business":
        return "Два варианта уже звучат. Минута — и понятно, какой садится на ролик."
    if whom:
        return (
            f"Два варианта {whom} уже звучат. Минута — и понятно, "
            "какой ближе к тому, что хотелось сказать."
        )
    return (
        "Два варианта уже звучат. Минута — и понятно, "
        "какой ближе к тому, что хотелось сказать."
    )


def keep_letter(contact: dict, step: int) -> str:
    """Письмо, если песня есть, а покупки нет. step 0..3 = дни 3, 7, 10, 14."""
    whom = _whom(contact)
    n = step if step < 3 else 3
    whom_for = _for(whom) if whom else ""
    if n == 0:
        if whom:
            return (
                f"Песня {whom_for} уже звучит. Осталось выбрать, какую оставить. "
                f"Получились два варианта, оба {whom_for}. "
                "Один теплее, другой живее. Они всё ещё здесь: открой и послушай, "
                "какой хочется включить ещё раз."
            )
        return (
            "Она уже звучит. Осталось выбрать, какую оставить. "
            "На днях получились два варианта. Один теплее, другой живее. "
            "Оба всё ещё здесь: открой и послушай, какой хочется включить ещё раз."
        )
    if n == 1:
        if whom:
            return (
                f"Песню {whom_for} уже можно поставить. "
                "Минута в наушниках — и слышно, та ли это. "
                "Оба варианта всё ещё здесь."
            )
        return (
            "Два варианта всё ещё ждут. Её уже можно включить вечером. "
            "Минута в наушниках — и слышно, та ли это песня."
        )
    if n == 2:
        if whom:
            return (
                "Если первые варианты прошли мимо — в студии можно собрать звучание иначе. "
                f"История {whom_for} уже внутри. "
                "Или открой и послушай те, что уже есть."
            )
        return (
            "Если первые варианты прошли мимо — в студии можно собрать звучание иначе. "
            "Историю заново рассказывать не нужно: она уже внутри. "
            "Или открой и послушай те, что уже есть."
        )
    if whom:
        return (
            f"Это последнее письмо про песню {whom_for}. "
            "Она сохранена. Послушать можно в любой вечер."
        )
    return (
        "Это последнее письмо про эту песню. "
        "Она сохранена. Послушать можно в любой вечер."
    )
